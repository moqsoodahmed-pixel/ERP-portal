/** Trend sparkline graphic matching dashboard reference */
export function SparklineTrend({ tone = 'ok', width = 90, height = 30 }) {
  const colors = {
    ok: '#3b82f6',
    warn: '#f59e0b',
    bad: '#ef4444',
    neutral: '#94a3b8',
    purple: '#7C3AED',
    peach: '#D98A2B',
    pink: '#DB4E82',
    skyblue: '#3D7BCC',
  };
  const color = colors[tone] || colors.ok;
  return (
    <svg width={width} height={height} viewBox="0 0 100 36" fill="none" aria-hidden="true" style={{ overflow: 'visible' }}>
      <defs>
        <linearGradient id={`spark-grad-${tone}`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor={color} stopOpacity="0.22" />
          <stop offset="100%" stopColor={color} stopOpacity="0.0" />
        </linearGradient>
      </defs>
      <path
        d="M2 28 Q 25 24, 45 18 T 85 8 L 98 6"
        fill="none"
        stroke={color}
        strokeWidth="2.2"
        strokeLinecap="round"
      />
      <path
        d="M2 28 Q 25 24, 45 18 T 85 8 L 98 6 L 98 36 L 2 36 Z"
        fill={`url(#spark-grad-${tone})`}
      />
    </svg>
  );
}

/** Map route or label to matching enterprise outline icon */
export function getNavIcon(pathOrLabel, size = 18) {
  const s = String(pathOrLabel).toLowerCase();
  if (s.includes('dashboard')) return <IconHome width={size} height={size} />;
  if (s.includes('business') || s.includes('profile')) return <IconBuilding width={size} height={size} />;
  if (s.includes('product')) return <IconCube width={size} height={size} />;
  if (s.includes('customer') || s.includes('client')) return <IconUsers width={size} height={size} />;
  if (s.includes('invoice')) return <IconFileText width={size} height={size} />;
  if (s.includes('filing') || s.includes('gst')) return <IconPercent width={size} height={size} />;
  if (s.includes('bill')) return <IconReceipt width={size} height={size} />;
  if (s.includes('tally-connector') || s.includes('connector')) return <IconPlug width={size} height={size} />;
  if (s.includes('tally')) return <IconRefresh width={size} height={size} />;
  if (s.includes('vendor')) return <IconStore width={size} height={size} />;
  if (s.includes('report')) return <IconBarChart width={size} height={size} />;
  if (s.includes('audit')) return <IconShield width={size} height={size} />;
  if (s.includes('queue')) return <IconClock width={size} height={size} />;
  return <IconFolder width={size} height={size} />;
}
